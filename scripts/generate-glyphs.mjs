// Extracts digit outlines (0-9) from the five bundled number fonts into src/render/glyphs.generated.ts and
// copies each font's OFL license, plus a NOTICE listing them, into the plugin. Keys are drawn from these paths, so they never depend on
// fonts installed on the Mac. Run with `npm run glyphs` after changing a font or weight; commit the output.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import opentype from "opentype.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Ids and order must match FONT_IDS in src/core/key-style.ts (a test checks). */
const FONTS = [
	{ id: "inter", name: "Inter", pkg: "inter", weight: 700, upstream: "rsms/inter" },
	{ id: "nunito", name: "Nunito", pkg: "nunito", weight: 800, upstream: "googlefonts/nunito" },
	{ id: "oswald", name: "Oswald", pkg: "oswald", weight: 600, upstream: "googlefonts/OswaldFont" },
	{ id: "jetbrains-mono", name: "JetBrains Mono", pkg: "jetbrains-mono", weight: 700, upstream: "JetBrains/JetBrainsMono" },
	{ id: "bitter", name: "Bitter", pkg: "bitter", weight: 700, upstream: "solmatas/BitterPro" },
];

const licenseDir = join(root, "com.austinzani.focus-keys.sdPlugin", "licenses", "fonts");
mkdirSync(licenseDir, { recursive: true });

const r = (n) => Math.round(n);

/**
 * Drops line segments that end where they start once rounded to whole font units, such as the "L690 20" opentype
 * emits right after "M690 20". They draw nothing in a filled outline and only bloat the generated paths.
 */
function withoutZeroLengthLines(path) {
	const out = new opentype.Path();
	let x;
	let y;
	for (const c of path.commands) {
		if (c.type === "L" && r(c.x) === x && r(c.y) === y) continue;
		out.commands.push(c);
		if (c.type !== "Z") [x, y] = [r(c.x), r(c.y)];
	}
	return out;
}
const tables = [];
const notices = [];
for (const f of FONTS) {
	const pkgDir = join(root, "node_modules", "@fontsource", f.pkg);
	const { version, license } = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
	if (license !== "OFL-1.1") throw new Error(`${f.name}: unexpected license ${license}`);
	const licenseText = readFileSync(join(pkgDir, "LICENSE"), "utf8");
	// The OFL body defines the term "Reserved Font Name"; a font reserves one in the copyright header above it.
	const header = licenseText.split(/This Font Software is licensed under/i)[0];
	if (header === licenseText || !/SIL Open Font License, Version 1\.1/i.test(licenseText)) throw new Error(`${f.name}: LICENSE is not the OFL 1.1 text`);
	if (/Reserved\s+Font\s+Names?/i.test(header)) throw new Error(`${f.name}: declares a Reserved Font Name; review before bundling`);
	copyFileSync(join(pkgDir, "LICENSE"), join(licenseDir, `${f.id}-OFL.txt`));

	const buf = readFileSync(join(pkgDir, "files", `${f.pkg}-latin-${f.weight}-normal.woff`));
	const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
	const digits = {};
	let top = -Infinity;
	let bottom = Infinity;
	for (const ch of "0123456789") {
		const glyph = font.charToGlyph(ch);
		if (glyph.index === 0) throw new Error(`${f.name}: no glyph for ${ch}`);
		// Font units, y flipped to SVG's downward axis, origin on the baseline at the pen position.
		const d = withoutZeroLengthLines(glyph.getPath(0, 0, font.unitsPerEm)).toPathData(0);
		const box = glyph.getBoundingBox();
		top = Math.max(top, box.y2);
		bottom = Math.min(bottom, box.y1);
		digits[ch] = { d, advance: r(glyph.advanceWidth), xMin: r(box.x1), xMax: r(box.x2) };
	}
	notices.push(`${f.name} ${f.weight}: @fontsource/${f.pkg} ${version} (github.com/${f.upstream}), license ${f.id}-OFL.txt`);
	tables.push({ id: f.id, name: f.name, source: `@fontsource/${f.pkg}@${version} (${f.weight})`, top: r(top), bottom: r(bottom), digits });
}

const out = `// Generated by scripts/generate-glyphs.mjs. Do not edit by hand.
// Digit outlines in font units (y down, baseline at 0). Fonts are SIL OFL 1.1; licenses in the plugin's licenses/fonts.

export type DigitGlyph = { d: string; advance: number; xMin: number; xMax: number };
/** top/bottom: highest and lowest extent of any digit, in font units above the baseline. */
export type GlyphFont = { id: string; name: string; source: string; top: number; bottom: number; digits: Record<string, DigitGlyph> };

export const GLYPH_FONTS: Record<string, GlyphFont> = ${JSON.stringify(Object.fromEntries(tables.map((t) => [t.id, t])), null, "\t")};
`;
writeFileSync(join(root, "src", "render", "glyphs.generated.ts"), out);
writeFileSync(
	join(licenseDir, "NOTICE.txt"),
	`Number fonts (generated by scripts/generate-glyphs.mjs)

The key numbers are drawn from digit outlines (0-9 only) extracted from the fonts below into
src/render/glyphs.generated.ts and bundled in bin/plugin.js. No font file is installed or loaded.
Each font is licensed under the SIL Open Font License 1.1, and the outline data derived from it
remains under that license. None declares a Reserved Font Name.

${notices.join("\n")}
`,
);
console.log(`wrote ${tables.length} fonts, ${out.length} bytes`);
